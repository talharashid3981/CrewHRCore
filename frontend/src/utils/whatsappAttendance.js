const timeZone = "Asia/Karachi";

const cleanText = (value) => String(value || "").replace(/[\r\n]+/g, " ").trim();

function formatAttendanceDate(date) {
  const [year, month, day] = date.split("-").map(Number);
  const dateValue = new Date(Date.UTC(year, month - 1, day, 12));
  const dateLabel = new Intl.DateTimeFormat("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(dateValue);
  const weekday = new Intl.DateTimeFormat("en-GB", {
    weekday: "long",
    timeZone: "UTC",
  }).format(dateValue);

  return `${dateLabel} (${weekday})`;
}

function formatAttendanceTime(value) {
  if (!value) return null;
  return new Intl.DateTimeFormat("en-US", {
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
    timeZone,
  }).format(new Date(value));
}

function formatWorkedTime(minutes) {
  const safeMinutes = Math.max(0, Math.floor(minutes || 0));
  const hours = Math.floor(safeMinutes / 60);
  const remainder = safeMinutes % 60;

  if (!remainder) return `${hours} ${hours === 1 ? "Hour" : "Hours"}`;
  if (!hours) return `${remainder} ${remainder === 1 ? "Minute" : "Minutes"}`;
  return `${hours} ${hours === 1 ? "Hour" : "Hours"} ${remainder} ${
    remainder === 1 ? "Minute" : "Minutes"
  }`;
}

export function formatAttendanceMessage(action, employee, attendance) {
  if (!["in", "out"].includes(action)) {
    throw new Error("This attendance action is not available.");
  }
  if (!attendance?.date || !attendance.checkIn) {
    throw new Error("The saved attendance details are unavailable to share.");
  }

  const lines = [
    "📋 Attendance Report",
    "",
    `📅 Date: ${formatAttendanceDate(attendance.date)}`,
    "",
    `👤 Name: ${cleanText(employee?.name) || "Employee"}`,
  ];
  const employeeId = cleanText(employee?.employeeId || employee?.employeeCode);
  const designation = cleanText(employee?.designation);
  const department = cleanText(employee?.department);

  if (employeeId) lines.push(`🆔 Employee ID: ${employeeId}`);
  if (designation) lines.push(`💼 Position: ${designation}`);
  if (department) lines.push(`🏢 Department: ${department}`);

  lines.push("", `🕒 Entry Time: ${formatAttendanceTime(attendance.checkIn)}`);

  if (action === "out") {
    if (!attendance.checkOut) {
      throw new Error("The saved check-out time is unavailable to share.");
    }

    lines.push(
      `🕒 Exit Time: ${formatAttendanceTime(attendance.checkOut)}`,
      `⏱️ Working Hours: ${formatWorkedTime(attendance.workedMinutes)}`,
    );
  }

  const status =
    action === "out"
      ? attendance.status && attendance.status !== "present"
        ? `Checked Out (${
            cleanText(attendance.status).replace(/^\w/, (letter) => letter.toUpperCase())
          })`
        : "Checked Out"
      : attendance.status === "late"
        ? "Late"
        : "Present";

  lines.push("", `✅ Status: ${status}`, "", "Generated by HRMS");
  return lines.join("\n");
}

async function copyToClipboard(text) {
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch (error) {
      console.error("Clipboard write failed:", error);
    }
  }

  const textArea = document.createElement("textarea");
  textArea.value = text;
  textArea.setAttribute("readonly", "");
  textArea.style.position = "fixed";
  textArea.style.opacity = "0";
  document.body.appendChild(textArea);
  textArea.select();

  try {
    return document.execCommand("copy");
  } finally {
    textArea.remove();
  }
}

export async function shareWhatsAppMessage(message) {
  if (navigator.share) {
    try {
      await navigator.share({ text: message });
      return "shared";
    } catch (error) {
      if (error?.name === "AbortError") {
        return "cancelled";
      }
      console.error("Web Share failed:", error);
    }
  }

  const isCoarsePointer = window.matchMedia?.("(pointer: coarse)").matches;
  const shareUrl = isCoarsePointer
    ? `https://wa.me/?text=${encodeURIComponent(message)}`
    : `https://web.whatsapp.com/send?text=${encodeURIComponent(message)}`;
  const openedWindow = window.open(shareUrl, "_blank");
  if (openedWindow) {
    openedWindow.opener = null;
    return "whatsapp";
  }

  try {
    if (await copyToClipboard(message)) return "copied";
  } catch (error) {
    console.error("Clipboard fallback failed:", error);
    return { status: "failed", error };
  }

  return { status: "failed", error: new Error("Clipboard access is unavailable.") };
}
